const now = new Date();
const iso = (daysFromNow: number) => {
  const d = new Date(now);
  d.setDate(d.getDate() + daysFromNow);
  return d.toISOString();
};

function gmpHistory(base: number, days: number) {
  const points = [];
  let v = base * 0.4;
  for (let i = days; i >= 0; i--) {
    v = Math.max(0, v + (Math.random() - 0.35) * base * 0.12);
    points.push({ timestamp: iso(-i), gmp: Math.round(v) });
  }
  return points;
}

